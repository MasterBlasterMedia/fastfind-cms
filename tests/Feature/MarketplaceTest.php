    }

    public function test_package_download_is_bounded_and_partial_files_are_removed(): void
    {
        config(['marketplace.max_package_bytes' => 100]);
        $package = $this->package('plugin');
        $this->serve($package);
        $this->actingAs($this->owner)->postJson(self::API.'/install', $this->selection($package))->assertUnprocessable()
            ->assertJsonPath('errors.marketplace.0', 'Marketplace response exceeds the size limit.');
        $this->assertRejectedWithoutCode();
    }

    public function test_download_host_is_resolved_independently_and_private_targets_are_rejected(): void
    {
        $package = $this->package('plugin');
        $this->serve($package);
        app()->instance(DnsResolver::class, new class extends DnsResolver {
            public function addresses(string $host): array { return [$host === 'market.example.test' ? '93.184.215.14' : '127.0.0.1']; }
        });
        $this->actingAs($this->owner)->postJson(self::API.'/install', $this->selection($package))->assertUnprocessable();
        Http::assertSentCount(1);
        $this->assertRejectedWithoutCode();
    }

    public function test_catalog_cannot_supply_a_new_publisher_key_or_client_download_url(): void
    {
        $package = $this->package('plugin');
        $package['publisher'] = 'unknown';
        $package['public_key'] = config('plugins.publishers.test-publisher');
        $this->serve($package);
        $this->actingAs($this->owner)->postJson(self::API.'/install', [...$this->selection($package), 'url' => self::DOWNLOAD,
            'public_key' => $package['public_key']])->assertUnprocessable();
        Http::assertSentCount(1);
        $this->assertRejectedWithoutCode();
    }

    public function test_owner_authorization_precedes_remote_fetch_and_install_validation(): void
    {
        $this->getJson(self::API)->assertUnauthorized();
        $this->postJson(self::API.'/install', [])->assertUnauthorized();
        foreach (['admin', 'editor', 'viewer'] as $role) {
            $this->flushSession();
            $user = User::create(['name' => $role, 'email' => $role.'@example.test', 'password' => 'long-test-password', 'role' => $role, 'is_active' => true]);
            $this->actingAs($user)->getJson(self::API)->assertForbidden();
            $this->postJson(self::API.'/install', [])->assertForbidden();
        }
        Http::assertNothingSent();
    }

    private function resolveTo(array $addresses): void
    {
        app()->instance(DnsResolver::class, new class($addresses) extends DnsResolver {
            public function __construct(private array $result) {}
            public function addresses(string $host): array { return $this->result; }
        });
    }

    private function package(string $type): array
    {
        $manifest = ['id' => $type === 'plugin' ? 'example/market' : 'market-theme', 'name' => 'Marketplace example',
            'version' => '1.0.0', 'description' => 'A signed marketplace package'];
        $manifest += $type === 'plugin'
            ? ['entry' => 'plugin.php', 'requires' => ['fastfind' => '^1.0', 'php' => '^8.3'], 'permissions' => []]
            : ['layout' => 'minimal', 'requires' => ['fastfind' => '^1.0'], 'defaults' => ['accent' => '#3159d9', 'font' => 'serif', 'width' => 'normal']];
        $file = $this->directory.'/'.Str::uuid().'.zip';
        $zip = new ZipArchive;
        $zip->open($file, ZipArchive::CREATE | ZipArchive::OVERWRITE);
        $zip->addFromString($type.'.json', json_encode($manifest));
        if ($type === 'plugin') $zip->addFromString('plugin.php', '<?php app()->instance("marketplace.executed", true); return new class extends \\App\\Plugins\\AbstractPlugin { public function register(\\App\\Plugins\\PluginContext $context): void {} };');
        $zip->close();
        $body = file_get_contents($file);
        return ['type' => $type, 'manifest' => $manifest, 'publisher' => 'test-publisher', 'body' => $body,
            'download' => ['url' => self::DOWNLOAD, 'sha256' => hash('sha256', $body), 'signature' => base64_encode(sodium_crypto_sign_detached($body, $this->secret))]];
    }

    private function catalog(array $packages): array
    {
        $catalog = ['schema_version' => 1, 'name' => 'Test marketplace', 'plugins' => [], 'themes' => []];
        foreach ($packages as $package) $catalog[$package['type'].'s'][] = array_diff_key($package, ['body' => true, 'type' => true]);
        return $catalog;
    }

    private function serve(array $package, ?string $body = null): void
    {
        Http::fake(fn ($request) => match ($request->url()) {
            self::CATALOG => Http::response($this->catalog([$package])),
            self::DOWNLOAD => Http::response($body ?? $package['body'], 200, ['Content-Type' => 'application/zip']),
            default => null,
        });
    }

    private function selection(array $package): array
    {
        return ['type' => $package['type'], 'id' => $package['manifest']['id'], 'version' => $package['manifest']['version'], 'sha256' => $package['download']['sha256']];
    }

    private function assertDownloadsClean(): void { $this->assertSame([], glob($this->directory.'/downloads/*') ?: []); }

    private function assertRejectedWithoutCode(): void
    {
        $this->assertDatabaseCount('plugin_installations', 0);
        $this->assertNull(SiteSetting::find('theme_packages'));
        $this->assertFalse(app()->bound('marketplace.executed'));
        $this->assertDownloadsClean();
    }
}
