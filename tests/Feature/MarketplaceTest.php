<?php

namespace Tests\Feature;

use App\Marketplace\DnsResolver;
use App\Models\PluginInstallation;
use App\Models\SiteSetting;
use App\Models\User;
use App\Services\ThemeManager;
use GuzzleHttp\Handler\CurlFactory;
use GuzzleHttp\Psr7\Request as PsrRequest;
use Illuminate\Foundation\Testing\RefreshDatabase;
use Illuminate\Support\Facades\File;
use Illuminate\Support\Facades\Http;
use Illuminate\Support\Str;
use PHPUnit\Framework\Attributes\DataProvider;
use Tests\TestCase;
use ZipArchive;

class MarketplaceTest extends TestCase
{
    use RefreshDatabase;

    private const CATALOG = 'https://market.example.test/catalog.json';
    private const DOWNLOAD = 'https://downloads.example.test/package.zip';
    private const API = '/api/v1/studio/marketplace';
    private string $directory;
    private string $secret;
    private User $owner;

    protected function setUp(): void
    {
        parent::setUp();
        $this->directory = storage_path('framework/testing/marketplace-'.Str::uuid());
        File::ensureDirectoryExists($this->directory, 0700);
        $pair = sodium_crypto_sign_keypair();
        $this->secret = sodium_crypto_sign_secretkey($pair);
        config([
            'marketplace.url' => self::CATALOG,
            'marketplace.hosts' => ['market.example.test', 'downloads.example.test'],
            'marketplace.site_url' => 'https://market.example.test/',
            'marketplace.download_path' => $this->directory.'/downloads',
            'plugins.package_path' => $this->directory.'/plugins',
            'themes.package_path' => $this->directory.'/themes',
            'plugins.publishers' => ['test-publisher' => base64_encode(sodium_crypto_sign_publickey($pair))],
        ]);
        $this->resolveTo(['93.184.215.14']);
        Http::preventStrayRequests();
        $this->owner = User::create(['name' => 'Owner', 'email' => 'owner@example.test', 'password' => 'long-test-password', 'role' => 'owner', 'is_active' => true]);
    }

    protected function tearDown(): void
    {
        // The directory is generated by this test beneath the isolated testing root.
        if (isset($this->directory)) File::deleteDirectory($this->directory);
        parent::tearDown();
    }

    public function test_unconfigured_marketplace_is_informative_and_makes_no_network_request(): void
    {
        config(['marketplace.url' => null, 'marketplace.site_url' => null]);
        $this->actingAs($this->owner)->getJson(self::API)->assertOk()->assertJsonPath('configured', false)
            ->assertJsonPath('source', 'unconfigured')->assertJsonPath('items', [])->assertJsonPath('site_url', null);
        Http::assertNothingSent();
    }

    public function test_catalog_exposes_reviewable_metadata_and_pins_a_validated_address(): void
    {
        $package = $this->package('plugin');
        $optionsSeen = null;
        $transportError = null;
        Http::fake(function ($request, $options) use ($package, &$optionsSeen, &$transportError) {
            $optionsSeen = $options;
            // Validate the options against the actual cURL transport without opening a socket.
            // This catches options silently ignored or rejected by Guzzle's real handler.
            try {
                $factory = new CurlFactory(1);
                $handle = $factory->create(new PsrRequest('GET', self::CATALOG), $options);
                $factory->release($handle);
            } catch (\Throwable $error) { $transportError = $error->getMessage(); }
            return Http::response($this->catalog([$package]));
        });
        $response = $this->actingAs($this->owner)->getJson(self::API)->assertOk()->assertJsonPath('configured', true)
            ->assertJsonPath('items.0.id', 'example/market')->assertJsonPath('items.0.can_install', true);
        $this->assertNull($transportError);
        $this->assertSame(['market.example.test:443:93.184.215.14'], $optionsSeen['curl'][CURLOPT_RESOLVE]);
        $this->assertSame('', $optionsSeen['proxy']);
        $this->assertFalse($optionsSeen['allow_redirects']);
        $this->assertFalse($optionsSeen['decode_content']);
        $this->assertArrayNotHasKey('download', $response->json('items.0'));
        $this->assertStringNotContainsString($package['download']['signature'], $response->getContent());
        $this->assertDatabaseCount('plugin_installations', 0);
        $this->assertFalse(app()->bound('marketplace.executed'));
    }

    public function test_signed_plugin_installs_inactive_without_executing_its_entry(): void
    {
        $package = $this->package('plugin');
        $this->serve($package);
        $this->actingAs($this->owner)->postJson(self::API.'/install', [...$this->selection($package), 'url' => 'http://127.0.0.1/private'])
            ->assertCreated()->assertJsonPath('status', 'installed')->assertJsonPath('id', 'example/market');
        $record = PluginInstallation::findOrFail('example/market');
        $this->assertSame('inactive', $record->status);
        $this->assertSame('1.0.0', $record->installed_version);
        $this->assertFileExists($record->path.'/plugin.php');
        $this->assertFalse(app()->bound('marketplace.executed'));
        $this->assertDownloadsClean();
        $this->getJson(self::API)->assertOk()->assertJsonPath('items.0.can_install', false)->assertJsonPath('items.0.installed_version', '1.0.0');
        Http::assertSentCount(3);
    }

    public function test_signed_theme_installs_through_the_shared_installer_without_switching_the_site(): void
    {
        $package = $this->package('theme');
        $this->serve($package);
        $this->actingAs($this->owner)->postJson(self::API.'/install', $this->selection($package))
            ->assertCreated()->assertJsonPath('type', 'theme')->assertJsonPath('id', 'market-theme');
        $this->assertSame('professional', app(ThemeManager::class)->current()['active']);
        $theme = collect(app(ThemeManager::class)->all())->firstWhere('id', 'market-theme');
        $this->assertSame('package', $theme['source']);
        $this->assertSame('test-publisher', $theme['publisher']);
        $this->assertSame('1.0.0', $theme['version']);
        $this->assertDownloadsClean();
    }

    public static function unsafeUrls(): array
    {
        return array_map(fn ($url) => [$url], [
            'http://market.example.test/catalog.json', 'https://other.example.test/catalog.json',
            'https://user:secret@market.example.test/catalog.json', 'https://market.example.test:8443/catalog.json',
            'https://market.example.test/catalog.json#fragment', 'https://127.0.0.1/catalog.json',
            'https://market.example.test.evil.test/catalog.json', 'https://market.example.test\\@127.0.0.1/',
        ]);
    }

    #[DataProvider('unsafeUrls')]
    public function test_unapproved_or_ambiguous_urls_are_rejected_before_http(string $url): void
    {
        config(['marketplace.url' => $url]);
        $this->actingAs($this->owner)->getJson(self::API)->assertUnprocessable();
        Http::assertNothingSent();
    }

    public static function unsafeAddresses(): array
    {
        return array_map(fn ($address) => [$address], [
            '127.0.0.1', '10.1.2.3', '169.254.169.254', '192.0.2.1', '0.0.0.0',
            '::1', 'fc00::1', '::ffff:127.0.0.1', '2002:7f00:1::',
        ]);
    }

    #[DataProvider('unsafeAddresses')]
    public function test_private_reserved_and_transition_addresses_never_reach_http(string $address): void
    {
        $this->resolveTo([$address]);
        $this->actingAs($this->owner)->getJson(self::API)->assertUnprocessable();
        Http::assertNothingSent();
    }

    public function test_empty_dns_and_mixed_public_private_answers_fail_closed(): void
    {
        foreach ([[], ['93.184.215.14', '127.0.0.1']] as $addresses) {
            $this->resolveTo($addresses);
            $this->actingAs($this->owner)->getJson(self::API)->assertUnprocessable();
        }
        Http::assertNothingSent();
    }

    public function test_redirects_are_rejected_without_following_the_location(): void
    {
        Http::fake([self::CATALOG => Http::response('', 302, ['Location' => 'http://127.0.0.1/private'])]);
        $this->actingAs($this->owner)->getJson(self::API)->assertUnprocessable();
        Http::assertSentCount(1);
    }

    public function test_download_redirects_do_not_escape_the_allowed_hosts_or_leave_files(): void
    {
        $package = $this->package('plugin');
        Http::fake(fn ($request) => $request->url() === self::CATALOG
            ? Http::response($this->catalog([$package]))
            : Http::response('', 302, ['Location' => 'http://127.0.0.1/private']));
        $this->actingAs($this->owner)->postJson(self::API.'/install', $this->selection($package))->assertUnprocessable()
            ->assertJsonPath('errors.marketplace.0', 'Marketplace response unavailable. Redirects are not followed.');
        Http::assertSentCount(2);
        $this->assertRejectedWithoutCode();
    }

    public function test_invalid_catalog_schema_and_duplicate_ids_are_rejected(): void
    {
        $package = $this->package('plugin');
        $catalog = $this->catalog([$package]);
        Http::fake(function () use (&$catalog) { return Http::response($catalog); });
        $catalog['schema_version'] = 2;
        $this->actingAs($this->owner)->getJson(self::API)->assertUnprocessable()
            ->assertJsonPath('errors.marketplace.0', 'Marketplace catalog does not match schema version 1.');
        $catalog = $this->catalog([$package, $package]);
        $this->getJson(self::API)->assertUnprocessable()
            ->assertJsonPath('errors.marketplace.0', 'The catalog must list only one release per package ID and type.');
        $this->assertRejectedWithoutCode();
    }

    public function test_catalog_response_size_is_bounded_without_content_length(): void
    {
        config(['marketplace.max_catalog_bytes' => 100]);
        Http::fake([self::CATALOG => Http::response(str_repeat('a', 101))]);
        $this->actingAs($this->owner)->getJson(self::API)->assertUnprocessable()
            ->assertJsonPath('errors.marketplace.0', 'Marketplace response exceeds the size limit.');
        Http::assertSentCount(1);
    }

    public function test_untrusted_and_incompatible_releases_are_displayed_but_cannot_be_downloaded(): void
    {
        $package = $this->package('plugin');
        $package['publisher'] = 'untrusted-publisher';
        $package['manifest']['requires']['fastfind'] = '^99.0';
        $this->serve($package);
        $this->actingAs($this->owner)->getJson(self::API)->assertOk()->assertJsonPath('items.0.can_install', false)
            ->assertJsonCount(2, 'items.0.issues');
        $this->postJson(self::API.'/install', $this->selection($package))->assertUnprocessable();
        Http::assertNotSent(fn ($request) => $request->url() === self::DOWNLOAD);
    }

    public function test_install_refetches_catalog_and_rejects_stale_version_or_digest(): void
    {
        $package = $this->package('plugin');
        $this->serve($package);
        foreach ([['version' => '0.9.0'], ['sha256' => str_repeat('0', 64)]] as $stale) {
            $this->actingAs($this->owner)->postJson(self::API.'/install', [...$this->selection($package), ...$stale])->assertUnprocessable()
                ->assertJsonPath('errors.marketplace.0', 'This marketplace release changed or is no longer listed. Refresh the catalog before installing.');
        }
        Http::assertSentCount(2);
        Http::assertNotSent(fn ($request) => $request->url() === self::DOWNLOAD);
    }

    public function test_changed_download_bytes_fail_integrity_and_are_cleaned_up(): void
    {
        $package = $this->package('plugin');
        $this->serve($package, $package['body'].'tampered');
        $this->actingAs($this->owner)->postJson(self::API.'/install', $this->selection($package))->assertUnprocessable()
            ->assertJsonPath('errors.marketplace.0', 'Downloaded package integrity verification failed.');
        $this->assertRejectedWithoutCode();
    }

    public function test_invalid_signature_cannot_authorize_an_otherwise_matching_download(): void
    {
        $package = $this->package('plugin');
        $package['download']['signature'] = base64_encode(str_repeat('x', SODIUM_CRYPTO_SIGN_BYTES));
        $this->serve($package);
        $this->actingAs($this->owner)->postJson(self::API.'/install', $this->selection($package))->assertUnprocessable()
            ->assertJsonPath('errors.marketplace.0', 'Downloaded package signature verification failed.');
        $this->assertRejectedWithoutCode();
    }

    public static function mismatches(): array
    {
        return [['id', 'example/other'], ['version', '2.0.0'], ['description', 'A misleading description']];
    }

    #[DataProvider('mismatches')]
    public function test_signed_archive_manifest_must_match_the_catalog(string $field, string $value): void
    {
        $package = $this->package('plugin');
        $package['manifest'][$field] = $value;
        $this->serve($package);
        $this->actingAs($this->owner)->postJson(self::API.'/install', $this->selection($package))->assertUnprocessable();
